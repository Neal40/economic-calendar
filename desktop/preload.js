const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("desktop", {
  platform: process.platform, // "darwin" = version Mac (libellés propres à la version Mac)
  journalGet: () => ipcRenderer.invoke("journal:get"),
  journalSync: (interactive) => ipcRenderer.invoke("journal:sync", interactive),
  journalAddIds: (ids) => ipcRenderer.invoke("journal:addIds", ids),
  journalImport: (kind, rows) => ipcRenderer.invoke("journal:import", kind, rows),
  tsxBars: (sym, from, to) => ipcRenderer.invoke("tsx:bars", sym, from, to),
  journalLogout: () => ipcRenderer.invoke("journal:logout"),
  notionStatus: () => ipcRenderer.invoke("notion:status"),
  notionSetToken: (t) => ipcRenderer.invoke("notion:setToken", t),
  notionDb: (id) => ipcRenderer.invoke("notion:db", id),
  dataStatus: () => ipcRenderer.invoke("data:status"),
  comptesRead: () => ipcRenderer.invoke("comptes:read"),
  propSync: (firm) => ipcRenderer.invoke("propsync:run", firm),
  onPropSync: (cb) => ipcRenderer.on("propsync:progress", (e, p) => cb(p)),
  copierGetConfig: () => ipcRenderer.invoke("copier:getConfig"),
  copierSaveConfig: (c) => ipcRenderer.invoke("copier:saveConfig", c),
  copierStart: () => ipcRenderer.invoke("copier:start"),
  copierStop: () => ipcRenderer.invoke("copier:stop"),
  copierStatus: () => ipcRenderer.invoke("copier:status"),
  onCopierLog: (cb) => ipcRenderer.on("copier:log", (e, l) => cb(l)),
  dataSync: () => ipcRenderer.invoke("data:sync"),
  dataRead: (sym, from, to, res) => ipcRenderer.invoke("data:read", sym, from, to, res),
  dataReadTf: (sym, tf, from, to) => ipcRenderer.invoke("data:readTf", sym, tf, from, to),
  dataOpenDir: () => ipcRenderer.invoke("data:openDir"),
  dataImport: () => ipcRenderer.invoke("data:import"),
  onData: (cb) => { ipcRenderer.on("data:progress", (e, p) => cb("progress", p)); ipcRenderer.on("data:done", (e, r) => cb("done", r)); },
  notionChanged: (items, since) => ipcRenderer.invoke("notion:changed", items, since),
  notionBlocks: (id) => ipcRenderer.invoke("notion:blocks", id),
  notionCreate: (db, props, tpl) => ipcRenderer.invoke("notion:create", db, props, tpl),
  notionUpdate: (db, id, props) => ipcRenderer.invoke("notion:update", db, id, props),
  notionArchive: (id) => ipcRenderer.invoke("notion:archive", id),
  notionAppend: (parent, items) => ipcRenderer.invoke("notion:append", parent, items),
  notionCaption: (id, c) => ipcRenderer.invoke("notion:caption", id, c),
  notionDeleteBlock: (id) => ipcRenderer.invoke("notion:delblock", id),
  newsWeek: () => ipcRenderer.invoke("news:week"),
  storeGet: () => ipcRenderer.invoke("store:get"),
  storeSet: (d) => ipcRenderer.invoke("store:set", d),
});
